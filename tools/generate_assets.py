"""Regenerate flash assets. Requires numpy, Pillow and matplotlib.
Uses the frozen accepted dial, never redraws/repositions its labels.
"""
from pathlib import Path
import json
import math
import numpy as np
from PIL import Image
from matplotlib import colormaps
from matplotlib.colors import LinearSegmentedColormap
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/"firmware/assets"
OUT=ROOT/"firmware/generated"
OUT.mkdir(parents=True,exist_ok=True)
model=json.loads((ASSETS/"density_24h.json").read_text(encoding="utf-8-sig"))
p=np.array([[v[k] for k in ("a","b","c","d")] for v in model["coefficients"]])
mass=.25*(p[:,0]+p[:,1]/2+p[:,2]/3+p[:,3]/4)
prefix=np.r_[0,np.cumsum(mass)]
def primitive(c,u):
    return c[0]*u+c[1]*u*u/2+c[2]*u**3/3+c[3]*u**4/4
def unwrapped(z):
    turns=math.floor(z/24);x=z-turns*24;i=min(95,int(x*4));u=(x-i*.25)*4
    return turns+prefix[i]+.25*primitive(p[i],u)
origin=unwrapped(-.125)
half=unwrapped(12-.125)-origin
def dens(t):
    x=(t-.125)%24;i=min(95,int(x*4));u=(x-i*.25)*4;c=p[i]
    return ((c[3]*u+c[2])*u+c[1])*u+c[0]
times=[(.125+i*.25)%24 for i in range(96)]
for i,c in enumerate(p):
    roots=np.roots([3*c[3],2*c[2],c[1]]) if abs(c[3])>1e-20 else np.roots([2*c[2],c[1]])
    times.extend((.125+i*.25+float(np.real(u))*.25)%24 for u in roots if np.isreal(u) and 0<float(np.real(u))<1)
maximum=max([.5*dens(t)/(half if t<12 else 1-half) for t in times]+[.5*dens(12)/half,.5*dens(12)/(1-half)])
im=Image.open(ASSETS/"clockface_240.png").convert("RGBA")
assert im.size==(240,240)
background=Image.new("RGBA",im.size,"black")
background.alpha_composite(im)
rgb=np.asarray(background.convert("RGB"),dtype=np.uint16)
def rgb565(a):
    a=np.asarray(a,dtype=np.uint16)
    return ((a[...,0]>>3)<<11)|((a[...,1]>>2)<<5)|(a[...,2]>>3)
face=rgb565(rgb).flatten()
cmap=LinearSegmentedColormap.from_list("clock",colormaps["YlGnBu_r"](np.linspace(0,.75,256)))
palette=rgb565(np.rint(cmap(np.linspace(0,1,256))[:,:3]*255).astype(np.uint16))
header="""/* Generated by tools/generate_assets.py. */
#ifndef CLOCK_ASSETS_H
#define CLOCK_ASSETS_H
#include <stdint.h>
#define CLOCK_CENTER 119.5f
#define CLOCK_INNER_RADIUS (119.5f * .7375f)
extern const uint16_t clock_face[240*240];
extern const uint16_t clock_palette[256];
extern const double clock_model_coefficients[96][4];
extern const double clock_model_prefix[97];
extern const double clock_model_origin,clock_model_half_mass,clock_model_max_density;
#endif
"""
(OUT/"clock_assets.h").write_text(header,encoding="utf-8")
def array16(name,values):
    lines=[", ".join(f"0x{int(v):04x}" for v in values[i:i+12]) for i in range(0,len(values),12)]
    return f"const uint16_t {name}[{len(values)}] = {{\n    "+",\n    ".join(lines)+"\n};\n"
text='/* Generated from the accepted dial and periodic cubic density. */\n#include "clock_assets.h"\n'
text+=array16("clock_face",face)+array16("clock_palette",palette)
text+="const double clock_model_coefficients[96][4] = {\n"+",\n".join("    {"+", ".join(format(float(v),".17g") for v in row)+"}" for row in p)+"\n};\n"
text+="const double clock_model_prefix[97] = {\n    "+",\n    ".join(format(float(v),".17g") for v in prefix)+"\n};\n"
text+=f"const double clock_model_origin={origin:.17g};\nconst double clock_model_half_mass={half:.17g};\nconst double clock_model_max_density={maximum:.17g};\n"
(OUT/"clock_assets.c").write_text(text,encoding="utf-8")
print(f"Generated {len(face)} RGB565 pixels; F(12)={half:.15f}; max density={maximum:.15f}")

